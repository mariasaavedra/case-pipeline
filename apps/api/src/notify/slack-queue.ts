// =============================================================================
// Slack queue (users.db v18) — messages that post at a set time
// =============================================================================
// Today one kind: "consult_ready", the attorney's "LB's 1:00 PM Ready" message
// (consult-ready.ts), queued from M18 step 2 for the consult's time. P17's
// Slack Queue tab lists, edits and deletes them.
//
// One queued message per appointment: queueing again (a second prep) replaces
// the words and time of the one still waiting. Rows are keyed by the
// appointment's MONDAY id — the local id is regenerated by the nightly full
// sync.
//
// runSlackQueue() is the job (every minute, server.ts): it claims each due row
// (queued → sending, so two ticks can never post it twice), posts it, and
// marks it sent or failed. A message more than LATE_LIMIT_MIN overdue (the
// server was down) is not posted — "1:00 PM Ready" at 3 PM helps no one — but
// marked failed, so reception sees it and can send it by hand or retry.
// Deleting is a soft delete (status 'deleted'), so the audit trail can still
// say what it was.
// =============================================================================

import type BetterSqlite3 from "better-sqlite3";
import type { SlackPostResult } from "./slack.js";

type Database = BetterSqlite3.Database;

export const createSlackQueueTableSql = `
  CREATE TABLE IF NOT EXISTS slack_queue (
    id                     INTEGER PRIMARY KEY,
    kind                   TEXT NOT NULL,
    appointment_monday_id  TEXT,
    board_key              TEXT,
    text                   TEXT NOT NULL,
    send_at                TEXT NOT NULL,
    status                 TEXT NOT NULL DEFAULT 'queued',
    dry_run                INTEGER NOT NULL DEFAULT 0,
    error                  TEXT,
    sent_at                TEXT,
    created_by             TEXT,
    updated_by             TEXT,
    created_at             TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at             TEXT NOT NULL DEFAULT (datetime('now'))
  );
  CREATE INDEX IF NOT EXISTS idx_slack_queue_due ON slack_queue(status, send_at);
  CREATE INDEX IF NOT EXISTS idx_slack_queue_appt ON slack_queue(appointment_monday_id);
`;

export type SlackQueueStatus = "queued" | "sending" | "sent" | "failed" | "deleted";
export type SlackQueueKind = "consult_ready";

export interface SlackQueueRow {
  id: number;
  kind: SlackQueueKind;
  appointmentMondayId: string | null;
  boardKey: string | null;
  text: string;
  /** ISO UTC. */
  sendAt: string;
  status: SlackQueueStatus;
  dryRun: boolean;
  error: string | null;
  sentAt: string | null;
  createdBy: string | null;
  updatedBy: string | null;
  createdAt: string;
  updatedAt: string;
}

interface Raw {
  id: number; kind: SlackQueueKind; appointment_monday_id: string | null; board_key: string | null; text: string;
  send_at: string; status: SlackQueueStatus; dry_run: number; error: string | null; sent_at: string | null;
  created_by: string | null; updated_by: string | null; created_at: string; updated_at: string;
}

const toRow = (r: Raw): SlackQueueRow => ({
  id: r.id, kind: r.kind, appointmentMondayId: r.appointment_monday_id, boardKey: r.board_key, text: r.text,
  sendAt: r.send_at, status: r.status, dryRun: r.dry_run === 1, error: r.error, sentAt: r.sent_at,
  createdBy: r.created_by, updatedBy: r.updated_by, createdAt: r.created_at, updatedAt: r.updated_at,
});

/** Overdue by more than this and it is not posted (marked failed instead). */
export const LATE_LIMIT_MIN = 60;

export function getQueued(db: Database, id: number): SlackQueueRow | null {
  const r = db.prepare("SELECT * FROM slack_queue WHERE id = ?").get(id) as Raw | undefined;
  return r ? toRow(r) : null;
}

/** The message still waiting for this appointment, if any. */
export function queuedForAppointment(db: Database, appointmentMondayId: string): SlackQueueRow | null {
  const r = db
    .prepare(
      `SELECT * FROM slack_queue WHERE appointment_monday_id = ? AND kind = 'consult_ready' AND status IN ('queued', 'failed')
        ORDER BY id DESC LIMIT 1`,
    )
    .get(appointmentMondayId) as Raw | undefined;
  return r ? toRow(r) : null;
}

/** Queue (or re-queue) the appointment's consult-ready message. */
export function queueConsultReady(
  db: Database,
  e: { appointmentMondayId: string; boardKey: string; text: string; sendAt: string; by: string },
): { row: SlackQueueRow; replaced: boolean } {
  const existing = queuedForAppointment(db, e.appointmentMondayId);
  if (existing) {
    db.prepare(
      `UPDATE slack_queue SET text = ?, send_at = ?, board_key = ?, status = 'queued', error = NULL,
              updated_by = ?, updated_at = datetime('now') WHERE id = ?`,
    ).run(e.text, e.sendAt, e.boardKey, e.by, existing.id);
    return { row: getQueued(db, existing.id)!, replaced: true };
  }
  const r = db
    .prepare(
      `INSERT INTO slack_queue (kind, appointment_monday_id, board_key, text, send_at, created_by, updated_by)
       VALUES ('consult_ready', ?, ?, ?, ?, ?, ?)`,
    )
    .run(e.appointmentMondayId, e.boardKey, e.text, e.sendAt, e.by, e.by);
  return { row: getQueued(db, Number(r.lastInsertRowid))!, replaced: false };
}

/**
 * The Slack Queue tab: everything still waiting or failed, plus what went out
 * since `sentSince` (ISO UTC) — so reception can check this morning's.
 */
export function listQueue(db: Database, sentSince: string): SlackQueueRow[] {
  return (
    db
      .prepare(
        `SELECT * FROM slack_queue
          WHERE status IN ('queued', 'sending', 'failed') OR (status = 'sent' AND sent_at >= ?)
          ORDER BY send_at ASC, id ASC`,
      )
      .all(sentSince) as Raw[]
  ).map(toRow);
}

/**
 * Edit a waiting (or failed) message. A failed one goes back in the queue —
 * that is how "Retry" works. Null = it was sent or deleted meanwhile.
 */
export function editQueued(
  db: Database, id: number, patch: { text?: string; sendAt?: string }, by: string,
): SlackQueueRow | null {
  const r = db
    .prepare(
      `UPDATE slack_queue SET text = COALESCE(?, text), send_at = COALESCE(?, send_at), status = 'queued', error = NULL,
              updated_by = ?, updated_at = datetime('now')
        WHERE id = ? AND status IN ('queued', 'failed')`,
    )
    .run(patch.text ?? null, patch.sendAt ?? null, by, id);
  return r.changes ? getQueued(db, id) : null;
}

/** Soft delete; false = it was already sent (or is being sent right now). */
export function deleteQueued(db: Database, id: number, by: string): boolean {
  return (
    db
      .prepare(
        `UPDATE slack_queue SET status = 'deleted', updated_by = ?, updated_at = datetime('now')
          WHERE id = ? AND status IN ('queued', 'failed')`,
      )
      .run(by, id).changes > 0
  );
}

/**
 * A row left 'sending' by a crash mid-post may or may not be in Slack: failed,
 * with a reason that says to look first. Run once at startup.
 */
export function recoverInterrupted(db: Database): number {
  return db
    .prepare(
      `UPDATE slack_queue SET status = 'failed', error = 'Interrupted while sending — check Slack before retrying',
              updated_at = datetime('now') WHERE status = 'sending'`,
    )
    .run().changes;
}

export interface SlackQueueRunResult {
  sent: number[];
  failed: Array<{ id: number; error: string }>;
}

/** Post every due message. `post` is notify/slack's postEvent("consult_ready", …). */
export async function runSlackQueue(
  db: Database,
  deps: { post: (text: string) => Promise<SlackPostResult>; now?: () => Date },
): Promise<SlackQueueRunResult> {
  const now = (deps.now ?? (() => new Date()))();
  const out: SlackQueueRunResult = { sent: [], failed: [] };
  const due = db
    .prepare("SELECT * FROM slack_queue WHERE status = 'queued' AND send_at <= ? ORDER BY send_at ASC")
    .all(now.toISOString()) as Raw[];
  const fail = (id: number, error: string) => {
    db.prepare("UPDATE slack_queue SET status = 'failed', error = ?, updated_at = datetime('now') WHERE id = ?").run(error, id);
    out.failed.push({ id, error });
  };
  for (const raw of due) {
    const claimed = db
      .prepare("UPDATE slack_queue SET status = 'sending', updated_at = datetime('now') WHERE id = ? AND status = 'queued'")
      .run(raw.id).changes;
    if (!claimed) continue;
    const lateMin = (now.getTime() - Date.parse(raw.send_at)) / 60_000;
    if (lateMin > LATE_LIMIT_MIN) {
      fail(raw.id, `Not sent — over ${LATE_LIMIT_MIN} minutes late (the server was down)`);
      continue;
    }
    const r = await deps.post(raw.text);
    if (r.ok) {
      db.prepare(
        `UPDATE slack_queue SET status = 'sent', dry_run = ?, error = NULL, sent_at = ?, updated_at = datetime('now') WHERE id = ?`,
      ).run(r.dryRun ? 1 : 0, now.toISOString(), raw.id);
      out.sent.push(raw.id);
    } else {
      fail(raw.id, r.error);
    }
  }
  return out;
}
